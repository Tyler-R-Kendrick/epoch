function markdown(source) {
  return {
    cell_type: "markdown",
    metadata: {},
    source,
  };
}

function code(source, executionCount, output) {
  return {
    cell_type: "code",
    execution_count: executionCount,
    metadata: {},
    outputs: [
      {
        name: "stdout",
        output_type: "stream",
        text: output,
      },
    ],
    source,
  };
}

function runSnippet(source) {
  return execFileSync(process.execPath, ["--input-type=module"], {
    cwd: repoRoot,
    encoding: "utf8",
    input: source,
    maxBuffer: 1024 * 1024 * 16,
    stdio: ["pipe", "pipe", "pipe"],
  });
}

function notebookFor(definition) {
  let executionCount = 1;
  const cells = [
    markdown(`# ${definition.title}\n\n${definition.summary}\n\n${codeIntro}`),
  ];

  for (const section of definition.sections) {
    cells.push(markdown(`## ${section.heading}\n\n**Use when:** ${section.useWhen}\n\nThe next cell is the executable example.`));
    const output = runSnippet(section.code);
    cells.push(code(section.code, executionCount, output));
    executionCount += 1;
    cells.push(markdown(`**How to read the output:** ${section.explanation}`));
  }

  return {
    cells,
    metadata: {
      kernelspec: {
        display_name: "Node.js",
        language: "javascript",
        name: "nodejs",
      },
      language_info: {
        file_extension: ".js",
        mimetype: "application/javascript",
        name: "javascript",
      },
    },
    nbformat: 4,
    nbformat_minor: 5,
  };
}

